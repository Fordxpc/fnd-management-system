import assert from 'node:assert/strict';
import { canEditDepartmentProfile, canReviewResignation, restrictInchargeEditPayload, isValidISODate, validateLetterUpload, makeResignationAcceptanceLetter } from '../src/lib/resignation-policy.ts';
const editor = { id:'lead',department:'Ground Operations',isIncharge:true,status:'active' };
const target = { id:'staff',department:'Ground Operations' };
assert.equal(canEditDepartmentProfile({id:'a',role:'staff'}, editor, target), true);
assert.equal(canEditDepartmentProfile({id:'a',role:'staff'}, editor, {...target,department:'Maintenance'}), false);
assert.equal(canEditDepartmentProfile({id:'a',role:'staff'}, editor, {...target,isSmt:true}), false);
assert.equal(canEditDepartmentProfile({id:'a',role:'staff'}, editor, target, true), false);
assert.equal(canEditDepartmentProfile({id:'a',role:'manager'}, null, target), true);
assert.equal(canReviewResignation({id:'a',role:'staff'}, editor, target), true);
assert.equal(canReviewResignation({id:'a',role:'staff'}, editor, {...target, department:'Maintenance'}), false);
assert.equal(canReviewResignation({id:'a',role:'manager'}, editor, {...target,department:'Maintenance'}), true);
assert.equal(canReviewResignation({id:'a',role:'manager'}, {...target}, target), false);
assert.deepEqual(restrictInchargeEditPayload({name:'A',role:'manager',department:'Other',basicSalary:999,position:'Officer'}),{name:'A',position:'Officer'});
assert.equal(isValidISODate('2026-11-31'), false);
assert.equal(isValidISODate('2026-11-30'), true);
const pdf='data:application/pdf;base64,' + btoa('%PDF-1.7\nrelevant text');
assert.equal(validateLetterUpload(pdf)?.mime,'application/pdf');
assert.equal(validateLetterUpload('data:application/pdf;base64,'+btoa('not a PDF')),null);
const letter=makeResignationAcceptanceLetter({employeeName:'Adam Shakir',employeeSn:'SN-0038',department:'Ground Operations',lastWorkingDay:'2026-12-01',approvalDate:'2026-11-06',approvingOfficer:'Manager'});
assert.ok(letter.includes('01 December 2026'));
assert.ok(letter.includes('electronic draft'));
console.log('resignation policy tests passed');
