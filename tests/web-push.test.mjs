import assert from 'node:assert/strict';
import { generateKeyPairSync, verify as verifySignature } from 'node:crypto';
import { getVapidAuthorization, isTrustedPushEndpoint } from '../src/lib/web-push.ts';
const { privateKey, publicKey } = generateKeyPairSync('ec',{ namedCurve:'prime256v1' });
const jwk = privateKey.export({ format:'jwk' });
const publicKeyUrl = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x,'base64url'),Buffer.from(jwk.y,'base64url')]).toString('base64url');
const endpoint = 'https://fcm.googleapis.com/fcm/send/test';
assert.ok(isTrustedPushEndpoint(endpoint));
assert.ok(isTrustedPushEndpoint('https://web.push.apple.com/qabc'));
assert.equal(isTrustedPushEndpoint('http://fcm.googleapis.com/x'), false);
assert.equal(isTrustedPushEndpoint('https://fcm.googleapis.com.attacker.com/x'), false);
assert.equal(isTrustedPushEndpoint('https://127.0.0.1:1234/api'), false);
const authorization = await getVapidAuthorization(endpoint, {VAPID_PUBLIC_KEY:publicKeyUrl,VAPID_PRIVATE_KEY:jwk.d,VAPID_SUBJECT:'mailto:team@example.com'});
assert.ok(authorization.startsWith('vapid t='));
const token = authorization.split('vapid t=')[1].split(',')[0];
const [header,payload,sig] = token.split('.');
assert.equal(JSON.parse(Buffer.from(payload,'base64url')).aud,'https://fcm.googleapis.com');
assert.equal(JSON.parse(Buffer.from(header,'base64url')).alg,'ES256');
assert.equal(verifySignature('sha256',Buffer.from(`${header}.${payload}`),{key:publicKey,dsaEncoding:'ieee-p1363'},Buffer.from(sig,'base64url')),true);
console.log('PASS VAPID token signature and trusted endpoints');
