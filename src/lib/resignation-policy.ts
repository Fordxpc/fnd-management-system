/** FND HR resignation and departmental access rules. No AI decision-making. */
export type StaffIdentity = { id?: string | null; department?: string | null; isIncharge?: boolean | null; isSmt?: boolean | null; status?: string | null };
export type AccountIdentity = { id?: string | null; role?: string | null };

const norm = (v: unknown) => String(v || '').trim().toLowerCase();
export const globalHR = (role: unknown) => ['developer', 'manager', 'admin', 'owner'].includes(norm(role));

export function isOwnDepartmentIncharge(actor: AccountIdentity, actorStaff: StaffIdentity | null | undefined, targetStaff: StaffIdentity): boolean {
  return Boolean(actor?.id && actorStaff?.id && actorStaff.isIncharge && norm(actorStaff.department) &&
    norm(actorStaff.department) === norm(targetStaff.department) &&
    norm(actorStaff.status || 'active') === 'active');
}

export function canEditDepartmentProfile(actor: AccountIdentity, editor: StaffIdentity | null | undefined, target: StaffIdentity, protectedAccount = false): boolean {
  if (globalHR(actor.role)) return true;
  return !protectedAccount && !target.isSmt && isOwnDepartmentIncharge(actor, editor, target);
}

/** In-Charges cannot change department, identity, salary, roles, status, permissions, or other protected fields. */
export const INCHARGE_EDITABLE_FIELDS = ['name', 'position', 'phone', 'gender', 'photoBase64'] as const;
export function restrictInchargeEditPayload(value: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const field of INCHARGE_EDITABLE_FIELDS) if (value[field] !== undefined) out[field] = value[field];
  return out;
}

export function canReviewResignation(actor: AccountIdentity, actorStaff: StaffIdentity | null | undefined, targetStaff: StaffIdentity): boolean {
  if (!actor?.id || !targetStaff?.id || String(actorStaff?.id || '') === String(targetStaff.id)) return false;
  return globalHR(actor.role) || isOwnDepartmentIncharge(actor, actorStaff, targetStaff);
}

export function isValidISODate(value: unknown): value is string {
  const date = String(value || '');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return false;
  const parsed = new Date(`${date}T00:00:00.000Z`);
  return !Number.isNaN(parsed.valueOf()) && parsed.toISOString().slice(0, 10) === date;
}

const MAX_ATTACHMENT_BYTES = 2 * 1024 * 1024;
/** Validate both declared media type and file signature to avoid spoofed uploads. */
export function validateLetterUpload(dataUrl: unknown): { mime: string; bytes: number } | null {
  if (typeof dataUrl !== 'string' || dataUrl.length > MAX_ATTACHMENT_BYTES * 1.45 + 100) return null;
  const match = /^data:(application\/pdf|image\/png|image\/jpeg);base64,([A-Za-z0-9+/]+={0,2})$/.exec(dataUrl);
  if (!match || match[2].length % 4 !== 0) return null;
  let decoded = '';
  try { decoded = atob(match[2]); } catch { return null; }
  if (!decoded.length || decoded.length > MAX_ATTACHMENT_BYTES) return null;
  const mime = match[1];
  const signatureValid = mime === 'application/pdf' ? decoded.startsWith('%PDF-') :
    mime === 'image/png' ? decoded.startsWith('\x89PNG\r\n\x1a\n') :
      decoded.startsWith('\xff\xd8\xff');
  return signatureValid ? { mime, bytes: decoded.length } : null;
}

const safeText = (v: unknown, limit = 160) => String(v || '').replace(/[\r\n\t]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, limit);
const formatDate = (iso: string) => isValidISODate(iso) ? new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-GB', {day:'2-digit',month:'long',year:'numeric',timeZone:'UTC'}) : iso;

/** Plain, deterministic draft. The approving manager remains responsible for final wording. */
export function makeResignationAcceptanceLetter(data: {
  employeeName: string; employeeSn: string; department: string; lastWorkingDay: string;
  approvalDate: string; approvingOfficer: string;
}): string {
  return [
    'FUNADHOO AIRPORT — RESIGNATION ACCEPTANCE',
    `Date: ${formatDate(data.approvalDate)}`,
    `To: ${safeText(data.employeeName)} (${safeText(data.employeeSn, 40)})`,
    `Department: ${safeText(data.department)}`,
    '',
    'Subject: Acceptance of Resignation',
    '',
    `Your resignation request has been approved, with your last working day recorded as ${formatDate(data.lastWorkingDay)}.`,
    'Please complete all applicable handover and clearance requirements with the department and Administration.',
    'Your final settlement and employment documentation will be handled under the applicable employment arrangements and policies.',
    '',
    `Approved by: ${safeText(data.approvingOfficer)}`,
    'Generated by FND Management System — electronic draft; official signature/authorization may be required.',
  ].join('\n');
}
